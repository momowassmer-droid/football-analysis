"""
One-command match analysis: point it at a folder of clips, get everything.

    python -m src.match data/raw/test1

For every video in the folder it:
  1. generates a config (model, resolution, tracker, filters),
  2. opens the interactive calibration if the clip isn't calibrated yet
     (you click the visible pitch landmarks -- the only manual step),
  3. runs the full per-clip workflow (detect -> track -> pitch coords ->
     teams -> ball -> analytics -> visualizations),
  4. assembles all clips into one global-id match dataset.

Re-running skips clips that are already calibrated, so it is cheap to resume.
Add --recalibrate to redo calibration, or pass a links JSON as 2nd arg to
apply manual cross-view merges.
"""

import re
import sys
from pathlib import Path

from src.workflow import run_match

VIDEO_EXTS = {".mp4", ".mov", ".avi", ".mkv", ".m4v"}
CONFIG_TEMPLATE = """\
# auto-generated by src.match
video:
  input: "{video}"
output:
  detections: "data/output/{tag}/detections/detections_raw.csv"
detection:
  model: "yolo11n.pt"
  imgsz: 1920
  nms_iou: 0.5
  confidence: 0.25
  stabilize: true   # cancel camera pan/zoom before tracking (Veo footage)
tracking:
  tracker: "config/trackers/bytetrack_occlusion.yaml"
field:
  enabled: true
  calibration: "{calib}"
  margin: 2.0
track_filter:
  enabled: true
  pitch_margin: 0.5
  min_inside_ratio: 0.60
stitching:
  enabled: true
  max_frame_gap: 30
  max_distance_px: 80.0
venue:
  name: "{venue_name}"
  pitch_length_m: {venue_length}
  pitch_width_m: {venue_width}
  surface: "{venue_surface}"
evaluate: true
"""


def _ask_venue() -> dict:
    """Always ask for the Spielstätte (venue) info when setting up a match."""
    print("\n--- Spielstätte (einmal pro Match) ---")
    name = input("  Name der Spielstätte [optional]: ").strip()
    length = input("  Platzlänge in Metern (Tor zu Tor) [105]: ").strip() or "105"
    width = input("  Platzbreite in Metern (Seitenlinie zu Seitenlinie) [68]: ").strip() or "68"
    surface = input("  Belag (Rasen/Kunstrasen/Hybridrasen) [Rasen]: ").strip() or "Rasen"
    return {"venue_name": name, "venue_length": float(length),
            "venue_width": float(width), "venue_surface": surface}


def _tag(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_")


def auto_match(folder: Path, match_name: str | None = None, frame_index: int = 0,
               recalibrate: bool = False, manual_links_json: Path | None = None) -> None:
    from tools.calibrate_field import calibrate_video  # imported here (pulls in cv2 GUI)

    videos = sorted(p for p in folder.iterdir() if p.suffix.lower() in VIDEO_EXTS)
    if not videos:
        print(f"No videos found in {folder}")
        return

    match_name = match_name or folder.name
    print(f"Found {len(videos)} clips in {folder} -> match '{match_name}'")

    venue = _ask_venue()   # Spielstätte immer abfragen

    configs = []
    for v in videos:
        tag = f"{match_name}_{_tag(v.stem)}"
        calib = Path("config/fields") / f"{tag}_calib.json"
        cfg = Path("config") / f"{tag}.yaml"
        cfg.parent.mkdir(parents=True, exist_ok=True)
        cfg.write_text(CONFIG_TEMPLATE.format(video=v.as_posix(), tag=tag,
                                              calib=calib.as_posix(), **venue),
                       encoding="utf-8")

        if recalibrate or not calib.exists():
            print(f"\n>>> Kalibriere '{v.name}': klicke die sichtbaren Feldpunkte "
                  f"(s=speichern, n=ueberspringen, q=abbrechen)")
            calibrate_video(v, calib, frame_index)
        else:
            print(f"  {v.name}: Kalibrierung vorhanden -> uebersprungen")

        configs.append(cfg)

    print("\nAlle Clips vorbereitet -> starte Verarbeitung + Zusammenfuehrung ...")
    run_match(configs, match_name, manual_links_json=manual_links_json)


def main() -> None:
    args = [a for a in sys.argv[1:] if a != "--recalibrate"]
    recalibrate = "--recalibrate" in sys.argv[1:]
    if not args:
        print(__doc__)
        return
    folder = Path(args[0])
    links = Path(args[1]) if len(args) > 1 else None
    auto_match(folder, recalibrate=recalibrate, manual_links_json=links)


if __name__ == "__main__":
    import multiprocessing
    multiprocessing.freeze_support()   # Windows: prevent spawn re-import recursion
    main()
